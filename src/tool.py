@tool
def calculator(expression: str) -> str:
    """数学计算工具。当用户需要做加、减、乘、除、括号等算术或数值计算时使用。
    入参 expression 为数学表达式字符串，例如 '(12 + 8) * 3'。"""
    try:
        return str(eval(expression, {"__builtins__": {}}, {}))
    except Exception as exc:  # noqa: BLE001
        return f"计算失败: {exc}"


